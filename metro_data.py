def _add_line(
    graph: WeightedGraph,
    stations: tuple[str, ...],
    times: tuple[float, ...],
) -> None:
    for station in stations:
        graph.add_vertex(station)
    for index, travel_time in enumerate(times):
        start = stations[index]
        end = stations[index + 1]
        graph.add_edge(start, end, travel_time)


def build_metro_graph() -> WeightedGraph:
    """Создать граф учебного фрагмента Московского метро."""
    graph = WeightedGraph()
    _add_line(graph, SOKOLNICHESKAYA, SOKOLNICHESKAYA_TIMES)
    _add_line(graph, ARBATSKO_POKROVSKAYA, ARBATSKO_POKROVSKAYA_TIMES)
    _add_line(graph, CIRCLE_LINE, CIRCLE_TIMES)
    graph.add_edge(CIRCLE_LINE[-1], CIRCLE_LINE[0], 3.0)

    for start, end, travel_time in TRANSFERS:
        graph.add_edge(start, end, travel_time)

    return graph
